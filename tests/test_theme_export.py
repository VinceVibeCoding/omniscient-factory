"""Theme exports: Windows Terminal schemes (JSONC) and herdr config, on tmp fixtures."""

from __future__ import annotations

import json
import tomllib
from datetime import UTC, datetime
from pathlib import Path

import pytest
from rich.console import Console

from omniscient.theme import PALETTES, ThemeError, theme_export
from omniscient.theme.export import (
    find_wt_settings,
    herdr_custom,
    herdr_snippet,
    pick_wt_settings,
    update_herdr_config,
    update_wt_settings,
    windows_terminal_scheme,
    write_herdr,
    write_windows_terminal,
)
from omniscient.theme.palettes import ANSI_NAMES

NOW = datetime(2026, 11, 13, 9, 30, tzinfo=UTC)


def _console() -> Console:
    return Console(record=True, width=120, color_system=None)


# ---- Windows Terminal ------------------------------------------------------------

WT = """﻿// This file was initially generated by Windows Terminal
{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "defaultProfile": "{2c4de342}", // Ubuntu
    /* the profiles */
    "profiles": { "list": [ { "name": "Ubuntu", "colorScheme": "Campbell" } ] },
    "schemes":
    [
        { "name": "Campbell", "background": "#0C0C0C", },
    ],
}
"""


def test_scheme_has_the_windows_terminal_shape() -> None:
    scheme = windows_terminal_scheme(PALETTES["omniscient"])
    assert scheme["name"] == "Omniscient · Omniscient (oracle)"
    assert set(ANSI_NAMES) <= set(scheme)
    assert {"background", "foreground", "cursorColor", "selectionBackground"} <= set(
        scheme
    )
    assert scheme["cursorColor"] == PALETTES["omniscient"].accent


def test_update_inserts_then_replaces_only_our_scheme() -> None:
    crlf = WT.replace("\n", "\r\n")
    first = update_wt_settings(crlf, windows_terminal_scheme(PALETTES["nord"]))
    second = update_wt_settings(first, windows_terminal_scheme(PALETTES["nord"]))
    assert first == second  # idempotent
    assert first.startswith("﻿// This file") and "/* the profiles */" in first
    assert "\r\n" in first and "\n" not in first.replace("\r\n", "")
    start = first.index('{\r\n            "name": "Omniscient · Nord"')
    end = first.index("},", start) + 2
    rest = first[:start] + first[end:]
    assert rest.replace(" ", "").replace("\r\n", "") == crlf.replace(" ", "").replace(
        "\r\n", ""
    )


def test_update_adds_a_schemes_list_when_missing() -> None:
    text = '{\n    "theme": "dark" // keep\n}\n'
    out = update_wt_settings(text, windows_terminal_scheme(PALETTES["kanagawa"]))
    assert '"theme": "dark" // keep' in out and '"schemes": [' in out
    empty = update_wt_settings(
        '{ "schemes": [] }', windows_terminal_scheme(PALETTES["nord"])
    )
    assert "Omniscient · Nord" in empty


def test_update_refuses_broken_jsonc() -> None:
    with pytest.raises(ThemeError):
        update_wt_settings(
            '{ "schemes": [ /* open', windows_terminal_scheme(PALETTES["nord"])
        )


def test_write_windows_terminal_backs_up_first(tmp_path: Path) -> None:
    users = tmp_path / "Users"
    settings = (
        users
        / "alex/AppData/Local/Packages/Microsoft.WindowsTerminal_8wekyb3d8bbwe"
        / "LocalState/settings.json"
    )
    settings.parent.mkdir(parents=True)
    settings.write_bytes(WT.encode("utf-8"))
    assert find_wt_settings(users) == (settings,)

    saved = write_windows_terminal(PALETTES["omniscient"], settings, NOW)

    assert saved.name == "settings.json.omniscient-20261113-093000.bak"
    assert saved.read_bytes() == WT.encode("utf-8")
    assert "Omniscient · Omniscient (oracle)" in settings.read_text(encoding="utf-8")
    again = write_windows_terminal(PALETTES["omniscient"], settings, NOW)
    assert again != saved and saved.exists()  # earlier backup kept


def test_pick_wt_settings_needs_exactly_one(tmp_path: Path) -> None:
    assert pick_wt_settings(tmp_path / "x.json") == tmp_path / "x.json"
    assert find_wt_settings(tmp_path / "nowhere") == ()


def test_export_prints_json_and_writes_with_path(tmp_path: Path) -> None:
    out = _console()
    theme_export("windows-terminal", "rose-pine", console=out)
    printed = out.export_text()
    scheme = json.loads(printed[: printed.index("}") + 1])
    assert scheme["name"] == "Omniscient · Rosé Pine"

    settings = tmp_path / "settings.json"
    settings.write_text('{ "schemes": [] }', encoding="utf-8")
    theme_export("windows-terminal", "rose-pine", True, path=settings, console=out)
    assert "Rosé Pine" in settings.read_text(encoding="utf-8")
    assert len(list(tmp_path.glob("settings.json.omniscient-*.bak"))) == 1
    with pytest.raises(ThemeError, match="Cible inconnue"):
        theme_export("kitty", "nord", console=out)


# ---- herdr -------------------------------------------------------------------------

HERDR = """onboarding = false

[theme]
name = "dracula"  # mine

[theme.custom]
accent = "#ff0000"

[keys]
prefix = "ctrl+b"
"""


def test_herdr_snippet_uses_builtins_or_custom_tokens() -> None:
    assert herdr_snippet(PALETTES["nord"]) == '[theme]\nname = "nord"\n'
    snippet = tomllib.loads(herdr_snippet(PALETTES["omniscient"]))
    assert snippet["theme"]["name"] == "tokyo-night"
    assert snippet["theme"]["custom"]["accent"] == PALETTES["omniscient"].accent
    assert herdr_custom(PALETTES["catppuccin-latte"]) == {}


def test_herdr_update_touches_only_theme_keys() -> None:
    out = tomllib.loads(update_herdr_config(HERDR, PALETTES["osaka-jade"]))
    assert out["onboarding"] is False and out["keys"] == {"prefix": "ctrl+b"}
    assert out["theme"]["custom"]["accent"] == PALETTES["osaka-jade"].accent
    builtin = tomllib.loads(update_herdr_config(HERDR, PALETTES["gruvbox"]))
    assert builtin["theme"] == {"name": "gruvbox", "custom": {}}


def test_write_herdr_backs_up(tmp_path: Path) -> None:
    config = tmp_path / "herdr" / "config.toml"
    config.parent.mkdir()
    config.write_text(HERDR, encoding="utf-8")
    saved = write_herdr(PALETTES["omniscient"], config, NOW)
    assert saved is not None and saved.read_text(encoding="utf-8") == HERDR
    assert "[keys]" in config.read_text(encoding="utf-8")
    fresh = tmp_path / "new" / "config.toml"
    assert write_herdr(PALETTES["nord"], fresh, NOW) is None
    assert tomllib.loads(fresh.read_text())["theme"]["name"] == "nord"


def test_write_windows_terminal_non_utf8_settings_is_a_french_theme_error(
    tmp_path: Path,
) -> None:
    settings = tmp_path / "settings.json"
    settings.write_bytes(b'{"schemes": [], "x": "\xff\xfe"}')

    with pytest.raises(ThemeError, match="UTF-8"):
        write_windows_terminal(PALETTES["omniscient"], settings, NOW)

    assert settings.read_bytes() == b'{"schemes": [], "x": "\xff\xfe"}'


def test_write_windows_terminal_missing_file_is_a_french_theme_error(
    tmp_path: Path,
) -> None:
    with pytest.raises(ThemeError, match="Impossible de lire ou d'écrire"):
        write_windows_terminal(PALETTES["omniscient"], tmp_path / "absent.json", NOW)


def test_write_herdr_unwritable_target_is_a_french_theme_error(tmp_path: Path) -> None:
    config = tmp_path / "config.toml"
    config.mkdir()  # a folder where the file should be: reading it fails

    with pytest.raises(ThemeError, match="Impossible de lire ou d'écrire"):
        write_herdr(PALETTES["omniscient"], config, NOW)
